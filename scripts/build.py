# ---------- checks on generated HTML ----------
problems = []
for slug in pages:
    text = open(os.path.join(DOCS, slug), encoding="utf-8").read()
    # every data row (tbody tr) must include at least one official link or be a non-link table (news/flags handled by data)
    for tbody in re.findall(r"<tbody>(.*?)</tbody>", text, re.S):
        for tr in re.findall(r"<tr>(.*?)</tr>", tbody, re.S):
            if "<a href" not in tr and slug not in ("requirements.html", "questions.html", "suggestions.html", "flagged.html", "strategy-lab.html"):
                problems.append(f"{slug}: row without any link: {tr[:80]}")
    for href in re.findall(r'href="([^"]+)"', text):
        if href.startswith("http"):
            if not href.startswith(OFFICIAL_HOSTS) and not href.startswith("https://github.com/karagemop466-tech/X2"):
                problems.append(f"{slug}: external link not on allow-list: {href}")
            continue
        if href.startswith("#"):
            continue
        target = href.split("#")[0]
        if not os.path.exists(os.path.join(DOCS, target)):
            problems.append(f"{slug}: broken internal link: {href}")
    if "http://" in text.replace("http://www.w3.org", ""):
        problems.append(f"{slug}: contains plain http:// link")

